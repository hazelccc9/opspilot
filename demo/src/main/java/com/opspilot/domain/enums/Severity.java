package com.opspilot.domain.enums;

/**
 * 告警/故障的严重级别。
 *
 * <p>级别决定响应时限、是否升级人工以及是否允许自动处置。OpsPilot 只做建议和 dry-run，
 * 因此级别不会直接触发真实写操作。
 */
public enum Severity {

    /** P1：最高优先级。核心链路不可用、大面积用户受影响，或资金/数据风险高。 */
    P1,

    /** P2：较高优先级。部分功能降级、错误率明显上升，但仍有可用路径。 */
    P2,

    /** P3：一般优先级。局部异常、趋势性劣化或低影响告警，可按正常排期处理。 */
    P3
}
