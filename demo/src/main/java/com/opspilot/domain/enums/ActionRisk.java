package com.opspilot.domain.enums;

/**
 * 处置动作的风险等级
 *
 * 风险等级用于决定审批策略和评测中的“风险是否被低估”：
 * Agent 可以给出比预期更高的风险（保守），但不能给出更低的风险（危险）。
 */
public enum ActionRisk {

    /** 低风险：影响范围小、可快速回滚，例如关闭非核心功能开关、补充只读诊断。 */
    LOW,

    /** 中风险：会影响部分用户或依赖，需要人工确认，例如扩容、调整连接池、熔断。 */
    MEDIUM,

    /** 高风险：可能造成更大范围影响或数据/资金风险，例如重启核心服务、回滚核心版本。 */
    HIGH
}
